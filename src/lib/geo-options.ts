/** The LANGUAGES subset valid for a given Labs country. Falls back to the full list for an
 * unrecognized/incomplete location (e.g. mid-typing), so the field never ends up with zero options. */
export function labsLanguagesFor(country: string): typeof LANGUAGES {
  const allowed = LABS_LANGUAGES_BY_COUNTRY[country];
  if (!allowed) return LANGUAGES;
  const set = new Set(allowed);
  const filtered = LANGUAGES.filter((l) => set.has(l.value));
  return filtered.length > 0 ? filtered : LANGUAGES;
}
